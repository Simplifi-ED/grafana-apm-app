import type { PluginOptions } from '@grafana/plugin-e2e';
import { defineConfig, devices } from '@playwright/test';
import { dirname } from 'node:path';

const pluginE2eAuth = `${dirname(require.resolve('@grafana/plugin-e2e'))}/auth`;
const configuredWorkers = process.env.PLAYWRIGHT_WORKERS;
const workers = configuredWorkers === undefined ? undefined : Number(configuredWorkers);

if (workers !== undefined && (!Number.isInteger(workers) || workers < 1)) {
  throw new Error('PLAYWRIGHT_WORKERS must be a positive integer');
}

/**
 * Read environment variables from file.
 * https://github.com/motdotla/dotenv
 */
// require('dotenv').config();

/**
 * See https://playwright.dev/docs/test-configuration.
 */
export default defineConfig<PluginOptions>({
  testDir: './tests',
  /* Run tests in files in parallel */
  fullyParallel: true,
  /* Fail the build on CI if you accidentally left test.only in the source code. */
  forbidOnly: !!process.env.CI,
  /* One CI retry only — 2 retries × 15s assertion timeouts blew the 15m job budget
     when pages failed to mount (22 failures → ~14m of hang before timeout cancel). */
  retries: process.env.CI ? 1 : 0,
  /* Fail individual tests faster so a broken mount doesn't eat the whole job. */
  timeout: 30_000,
  expect: { timeout: 10_000 },
  /* Cap CI concurrency — Grafana + plugin backend thrash under default workers. */
  workers: workers ?? (process.env.CI ? 2 : undefined),
  /* Reporter to use. See https://playwright.dev/docs/test-reporters */
  reporter: 'html',
  /* Shared settings for all the projects below. See https://playwright.dev/docs/api/class-testoptions. */
  use: {
    /* Base URL to use in actions like `await page.goto('/')`. */
    baseURL: process.env.GRAFANA_URL || 'http://127.0.0.1:3000',

    /* Collect trace when retrying the failed test. See https://playwright.dev/docs/trace-viewer */
    trace: 'on-first-retry',
  },

  /* Configure projects for major browsers */
  projects: [
    // 1. Login to Grafana and store the cookie on disk for use in other tests.
    {
      name: 'auth',
      testDir: pluginE2eAuth,
      testMatch: [/.*\.js/],
    },
    // 2. Run tests in Google Chrome. Every test will start authenticated as admin user.
    {
      name: 'chromium',
      use: {
        ...devices['Desktop Chrome'],
        storageState: 'playwright/.auth/admin.json',
      },
      dependencies: ['auth'],
    },
  ],
});
